/** How Socket.IO 4 frames the protocol over a WebSocket. */
export const TRANSPORT = `## Transport

Socket.IO 4 over a WebSocket: Engine.IO protocol 4 packets, Socket.IO
packets inside them, every payload JSON. A client needs no Socket.IO
library; this section is all the framing a WebSocket-only client writes and
reads (no HTTP long polling, no binary attachments).

1. Open a WebSocket to \`ws://<host>/socket.io/?EIO=4&transport=websocket\`
   (\`wss://\` over TLS; the path is the server's Socket.IO \`path\`,
   \`/socket.io\` unless the app changed it). Each WebSocket text message is
   one packet.
2. The server opens with Engine.IO's OPEN packet, \`0\` and a JSON object:
   \`0{"sid":"…","upgrades":[],"pingInterval":25000,"pingTimeout":20000,"maxPayload":1000000}\`.
3. The client connects to the main namespace with Socket.IO's CONNECT
   packet, \`40\`, carrying the handshake's \`auth\` (below):
   \`40{"token":"…","qd":{"protocol":5,"client":"my-game/1.0"}}\`.
4. The server accepts with CONNECT, \`40{"sid":"…"}\`, then sends
   \`qd:hello\`. Or it refuses with CONNECT_ERROR,
   \`44{"message":"…","data":{"code":"…"}}\`, and the socket is not connected.
5. An event is \`42\` and a JSON array, \`["<event>", <payload>]\`. An event
   that asks for an acknowledgement puts its ack id between the two:
   \`42<ackId>["qd:call",{…}]\`, and the server answers with an ACK packet,
   \`43<ackId>[<reply>]\`. Ack ids are the client's own counter for its
   connection; they are not a call's \`id\`.
6. The server sends PING, \`2\`, every \`pingInterval\` milliseconds; answer
   PONG, \`3\`, or the server closes the connection after \`pingTimeout\`. A
   client that hears nothing for \`pingInterval + pingTimeout\` has lost the
   connection.
7. A client leaves with Socket.IO's DISCONNECT, \`41\`, then closes the
   WebSocket itself. The server ends a socket with \`41\` and closes the
   WebSocket after it; a message longer than \`maxPayload\` bytes closes it
   too. The server sends \`41\` when it ends the socket's session (signed
   out, revoked or expired) or for a flooded channel: the client is then
   signed out. It forgets the user and what it cached, and connects again
   only when the app asks.`;

