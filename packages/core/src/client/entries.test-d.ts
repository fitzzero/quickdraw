describe("./client and ./client/core", () => {
  test("./client/core's functions are ./client's", () => {
    expectTypeOf(core.createQuickdrawConnection).toEqualTypeOf(client.createQuickdrawConnection);
    expectTypeOf(core.call).toEqualTypeOf(client.call);
    expectTypeOf(core.callData).toEqualTypeOf(client.callData);
    expectTypeOf(core.newId).toEqualTypeOf(client.newId);
    expectTypeOf(core.createPeerLink).toEqualTypeOf(client.createPeerLink);
    expectTypeOf(core.defineHost).toEqualTypeOf(client.defineHost);
    expectTypeOf(core.createServerCaller).toEqualTypeOf(client.createServerCaller);
    expectTypeOf<core.QuickdrawConnection>().toEqualTypeOf<client.QuickdrawConnection>();
  });

  test("./client/core leaves out the layers that need React or a QueryClient", () => {
    expectTypeOf(core).not.toHaveProperty("createQuickdrawClient");
    expectTypeOf(core).not.toHaveProperty("QuickdrawProvider");
    expectTypeOf(core).not.toHaveProperty("createInvalidationCoordinator");
    expectTypeOf(core).not.toHaveProperty("overlaysOf");
    expectTypeOf(core).not.toHaveProperty("sessionOf");
    expectTypeOf(core).not.toHaveProperty("liveDataOf");
  });
});
